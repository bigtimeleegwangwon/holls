    /**
     * 번호 → 구간명. errcode.py stage_of() 이식.
     */
    public static function stageOf(int|string $code): string
    {
        $n = (int)$code;
        return self::STAGES[(int)($n / 1000)] ?? '';
    }

    /**
     * 번호 → 상세. errcode.py what() 이식.
     *
     * @return array{code:int|string, stage:string, means:string, todo:string}
     */
    public static function what(int|string $code): array
    {
        $n   = is_numeric($code) ? (int)$code : 0;
        $row = self::TABLE[$n] ?? null;
        if ($row === null) {
            return ['code' => $code, 'stage' => '', 'means' => '', 'todo' => ''];
        }
        return ['code' => $n, 'stage' => self::stageOf($n), 'means' => $row[0], 'todo' => $row[1]];
    }

    /**
     * 전체 오류 표. errcode.py table() 이식.
     *
     * @return array<int,array{code:int, stage:string, means:string, todo:string}>
     */
    public static function table(): array
    {
        $out = [];
        foreach (self::TABLE as $code => $row) {
            $out[] = [
                'code'  => $code,
                'stage' => self::stageOf($code),
                'means' => $row[0],
                'todo'  => $row[1],
            ];
        }
        ksort($out);
        return $out;
    }
